/**
 * dashboardExport.js - what goes into a Dashboard download (T021, FR-2.4).
 *
 * Pure helpers, no file libraries: they turn the rows the Dashboard is
 * showing into one "export model" that both writers use (utils/exportPdf.js
 * and utils/exportExcel.js), so the PDF and the Excel file always agree.
 *
 * Rules (decided for T021):
 *   - A download is exactly what the person is looking at: the same view
 *     (By regulation / By Business Unit), the same filters, the same order.
 *   - Every role can download (FR-2.4). The rows are already scoped to the
 *     caller's tenant by the backend; nothing new is fetched for a download.
 *   - Status is written as words as well as colour ("Action needed"), so a
 *     printed or colour-blind reading never depends on colour (NFR-6), and
 *     Excel can filter on it. "Not set" when nobody has set it.
 *   - Removed (hidden) documents are never listed.
 *   - Every file says what it contains: when, by whom, view, filters, sort,
 *     row count and the status counts, plus "Status is set by people, never
 *     generated by AI."
 */
import { NOT_SET } from './regulationFilters';
import { isKnownStatus, statusLabel } from '../constants/status';
import { parseDueDate } from './roadmapDates';
import { displayName, parseTimestamp, unitEntry, visibleDocuments } from './dashboardTable';

export const AI_NOTE = 'Status is set by people, never generated by AI.';

const VIEW_LABEL = { regulation: 'By regulation', bu: 'By Business Unit' };

function text(value) {
  return String(value ?? '').trim();
}

/** "Printers (BU1)", or the bare code when the unit has no label. */
export function unitName(code, buLabelByCode) {
  const label = buLabelByCode[code];
  return label ? `${label} (${code})` : code;
}

/** A due date ("YYYY-MM-DD") as a Date at UTC midnight, or null. */
export function dueDateValue(value) {
  const parsed = parseDueDate(value);
  if (!parsed) return null;
  return new Date(Date.UTC(parsed.getFullYear(), parsed.getMonth(), parsed.getDate()));
}

/** A Firestore timestamp as its local calendar day, at UTC midnight, or null. */
export function dayValue(value) {
  const date = parseTimestamp(value);
  if (!date) return null;
  return new Date(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()));
}

function statusCell(entry) {
  const status = isKnownStatus(entry.status) ? entry.status : null;
  return { status, label: statusLabel(status), note: text(entry.note) };
}

/** One line per filter in use, in the filter bar's order; [] when none. */
export function describeFilters(filters, options = {}) {
  const lines = [];
  const pick = (key, values) => {
    const known = Object.fromEntries((options[key] || []).map((o) => [o.value, o.label]));
    return values
      .map((v) => known[v] || (v === NOT_SET ? (key === 'status' ? 'Not set' : 'Not specified') : v))
      .join(', ');
  };
  if (text(filters.q)) lines.push(`Search: "${text(filters.q)}"`);
  if (filters.status?.length) lines.push(`Status: ${pick('status', filters.status)}`);
  if (filters.domain?.length) lines.push(`Domain: ${pick('domain', filters.domain)}`);
  if (filters.bu?.length) lines.push(`Business Unit: ${pick('bu', filters.bu)}`);
  if (filters.country?.length) lines.push(`Country: ${pick('country', filters.country)}`);
  if (filters.region?.length) lines.push(`Region: ${pick('region', filters.region)}`);
  if (filters.dueFrom || filters.dueTo) {
    if (filters.dueFrom && filters.dueTo) lines.push(`Due date: ${filters.dueFrom} to ${filters.dueTo}`);
    else if (filters.dueFrom) lines.push(`Due date: on or after ${filters.dueFrom}`);
    else lines.push(`Due date: on or before ${filters.dueTo}`);
  }
  if (filters.docs === 'with') lines.push('Documents: has documents');
  if (filters.docs === 'without') lines.push('Documents: no documents');
  return lines;
}

/** Counts every Business Unit status shown in the export, most urgent first. */
export function statusCounts(model) {
  const counts = { action_needed: 0, pending: 0, compliant: 0, none: 0 };
  for (const row of model.rows) {
    const cells = model.view === 'bu' ? [row.status] : row.unitStatuses.map((u) => u.cell);
    for (const cell of cells) counts[cell.status || 'none'] += 1;
  }
  return counts;
}

/** "Regulator-Dashboard-2026-10-17-0930.pdf" (local time). */
export function exportFileName(extension, now = new Date()) {
  const pad = (n) => String(n).padStart(2, '0');
  const stamp = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}-${pad(now.getHours())}${pad(now.getMinutes())}`;
  return `Regulator-Dashboard-${stamp}.${extension}`;
}

/**
 * Builds the export model.
 *
 *   rows           the Dashboard's rows, already filtered and sorted
 *   view           'regulation' | 'bu'
 *   businessUnits  [{ code, label }] for unit names
 *   filters        current filters; filterOptions for their labels
 *   sortLabel      e.g. "Due date, ascending"
 *   generatedBy    the signed-in person's email
 */
export function buildExportModel({
  rows,
  view,
  businessUnits = [],
  filters,
  filterOptions = {},
  sortLabel,
  generatedBy = '',
  totalCount,
  now = new Date(),
}) {
  const buLabelByCode = Object.fromEntries(businessUnits.map((bu) => [bu.code, bu.label]));
  const filterLines = describeFilters(filters, filterOptions);

  const base = (reg) => ({
    id: reg.id,
    title: text(reg.title),
    abbreviatedTitle: text(reg.abbreviatedTitle),
    name: displayName(reg),
    dueDate: dueDateValue(reg.dueDate),
    domain: text(reg.domain),
    country: text(reg.country),
    region: text(reg.region),
    notes: text(reg.notes),
    added: dayValue(reg.createdAt),
    lastUpdated: dayValue(reg.lastUpdated || reg.createdAt),
  });

  let exportRows;
  if (view === 'bu') {
    exportRows = rows.map((reg) => {
      const entry = unitEntry(reg, reg.rowBu);
      return {
        ...base(reg),
        unitCode: reg.rowBu,
        unit: unitName(reg.rowBu, buLabelByCode),
        status: statusCell(entry),
        statusUpdated: dayValue(entry.updatedAt),
        documents: visibleDocuments(reg, reg.rowBu).map((d) => text(d.fileName)).filter(Boolean),
      };
    });
  } else {
    exportRows = rows.map((reg) => {
      const units = reg.businessUnitIds || [];
      return {
        ...base(reg),
        units: units.map((code) => unitName(code, buLabelByCode)),
        unitStatuses: units.map((code) => ({
          code,
          unit: unitName(code, buLabelByCode),
          cell: statusCell(unitEntry(reg, code)),
        })),
        documents: visibleDocuments(reg).map((d) => text(d.fileName)).filter(Boolean),
      };
    });
  }

  // Excel, By regulation: one status column per unit that appears in the rows.
  const unitColumns = [];
  if (view !== 'bu') {
    const seen = new Set();
    for (const row of exportRows) for (const u of row.unitStatuses) seen.add(u.code);
    const order = businessUnits.map((bu) => bu.code);
    const rank = (code) => (order.includes(code) ? order.indexOf(code) : order.length);
    unitColumns.push(
      ...[...seen]
        .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b))
        .map((code) => ({ code, name: unitName(code, buLabelByCode) }))
    );
  }

  const model = {
    title: 'Compliance Dashboard',
    view,
    viewLabel: VIEW_LABEL[view] || VIEW_LABEL.regulation,
    rowNoun: view === 'bu' ? 'Business Unit rows' : 'regulations',
    generatedAt: now,
    generatedBy,
    filterLines,
    sortLabel,
    rows: exportRows,
    totalCount: totalCount ?? exportRows.length,
    unitColumns,
  };
  model.counts = statusCounts(model);
  return model;
}

/** "3 of 12 regulations" or "12 regulations". */
export function rowCountLabel(model) {
  const shown = model.rows.length;
  return shown === model.totalCount ? `${shown} ${model.rowNoun}` : `${shown} of ${model.totalCount} ${model.rowNoun}`;
}

/** "Action needed 2 · Pending 3 · Compliant 5 · Not set 1" (zero counts left out). */
export function countsLabel(counts) {
  const parts = [
    ['Action needed', counts.action_needed],
    ['Pending', counts.pending],
    ['Compliant', counts.compliant],
    ['Not set', counts.none],
  ]
    .filter(([, n]) => n > 0)
    .map(([label, n]) => `${label} ${n}`);
  return parts.length ? parts.join(' · ') : 'None';
}

export function formatGeneratedAt(date) {
  return date.toLocaleString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  });
}

/** Dates held at UTC midnight, shown as "Oct 22, 2026". */
export function formatDay(date) {
  return date ? date.toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric', timeZone: 'UTC' }) : '';
}

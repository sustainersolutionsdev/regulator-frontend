/**
 * summarySlides.js - Generate Slides (second drop, Nov 16-30; DL-20 point 4).
 *
 * Turns an AI summary that is already on screen into a .pptx download that
 * opens in PowerPoint and Google Slides. It is built in the browser from the
 * summary the dialog holds, so it makes no AI call and costs nothing, and it
 * can only contain what the user is already allowed to see.
 *
 * Rules carried over from the summaries (DL-19):
 *  - the disclaimer is on every slide, and the first slide carries the
 *    AI-generated tag and the time the summary was generated;
 *  - status is always written as words as well as colour;
 *  - Business Units by name; contacts by name (email addresses stay in the app).
 *
 * pptxgenjs is loaded only when someone clicks Generate Slides (dynamic
 * import), so it adds nothing to the normal page load.
 */

const DISCLAIMER =
  'Generated by AI from information entered in Regulator. Review before using it. Material is for general information only and does not constitute professional or legal advice.';

// Brand tokens (design system). Arial: always installed, so slides look the
// same in PowerPoint and Google Slides (Inter may not be on the viewer's machine).
const FONT = 'Arial';
const TEAL = '0D7377';
const NAVY = '0F172A';
const GREY = '475569';
const LIGHT = 'F1F5F9';
const BORDER = 'CBD5E1';

// Text colours that pass WCAG AA on white, with a pale fill for the status cell.
const STATUS_STYLE = {
  compliant: { text: '15803D', fill: 'DCFCE7', word: 'Compliant' },
  pending: { text: 'B45309', fill: 'FEF3C7', word: 'Pending' },
  action_needed: { text: 'B91C1C', fill: 'FEE2E2', word: 'Action needed' },
  not_set: { text: GREY, fill: LIGHT, word: 'Not set' },
};

const W = 13.333; // LAYOUT_WIDE, 16:9
const MARGIN = 0.5;
const BODY_W = W - MARGIN * 2;
const PAGE_LINES = 36; // table text lines that fit on one slide at 11 pt, below the heading

function styleOf(status) {
  return STATUS_STYLE[status] || STATUS_STYLE.not_set;
}

function dueText(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso || '');
  if (!m) return '';
  const d = new Date(Date.UTC(+m[1], +m[2] - 1, +m[3]));
  return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' });
}

function generatedText(iso) {
  const d = iso ? new Date(iso) : null;
  if (!d || Number.isNaN(d.getTime())) return '';
  return d.toLocaleString('en-US', { day: 'numeric', month: 'short', year: 'numeric', hour: 'numeric', minute: '2-digit' });
}

function contactNames(contacts) {
  return (contacts || []).map((c) => c.name).filter(Boolean).join(', ');
}

function slug(text) {
  return (text || 'summary')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 50) || 'summary';
}

function today() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

/** Lines a cell needs, from its text length and the characters that fit on one line. */
function lines(text, perLine) {
  return Math.max(1, Math.ceil(String(text || '').length / perLine));
}

/** Split rows into slides by an estimate of how many text lines each row needs. */
export function paginate(rows, size, budget = PAGE_LINES) {
  const pages = [];
  let page = [];
  let used = 0;
  for (const row of rows) {
    const n = size(row);
    if (page.length && used + n > budget) {
      pages.push(page);
      page = [];
      used = 0;
    }
    page.push(row);
    used += n;
  }
  if (page.length) pages.push(page);
  return pages;
}

async function newDeck(title) {
  const { default: PptxGenJS } = await import('pptxgenjs');
  const pres = new PptxGenJS();
  pres.layout = 'LAYOUT_WIDE';
  pres.author = 'Regulator by Sustainer';
  pres.company = 'Sustainer';
  pres.title = title;
  pres.defineSlideMaster({
    title: 'REGULATOR',
    background: { color: 'FFFFFF' },
    objects: [
      { rect: { x: 0, y: 0, w: W, h: 0.12, fill: { color: TEAL } } },
      { text: { text: 'Regulator', options: { x: MARGIN, y: 6.95, w: 1.6, h: 0.35, fontFace: FONT, fontSize: 9, bold: true, color: TEAL } } },
      { text: { text: DISCLAIMER, options: { x: 2.1, y: 6.9, w: 9.9, h: 0.45, fontFace: FONT, fontSize: 8, color: GREY, valign: 'middle' } } },
    ],
    slideNumber: { x: 12.3, y: 6.98, w: 0.6, h: 0.3, fontFace: FONT, fontSize: 9, color: GREY, align: 'right' },
  });
  return pres;
}

function heading(slide, text, sub) {
  slide.addText(text, { x: MARGIN, y: 0.35, w: BODY_W, h: 0.6, fontFace: FONT, fontSize: 24, bold: true, color: NAVY });
  if (sub) slide.addText(sub, { x: MARGIN, y: 0.95, w: BODY_W, h: 0.35, fontFace: FONT, fontSize: 12, color: GREY });
}

function titleSlide(pres, { kicker, title, sub, when, short, extra }) {
  const s = pres.addSlide({ masterName: 'REGULATOR' });
  s.addText(kicker, { x: MARGIN, y: 0.6, w: BODY_W, h: 0.35, fontFace: FONT, fontSize: 12, color: GREY });
  s.addText(title, { x: MARGIN, y: 1.0, w: BODY_W, h: 0.9, fontFace: FONT, fontSize: 32, bold: true, color: NAVY, valign: 'top', fit: 'shrink' });
  if (sub) s.addText(sub, { x: MARGIN, y: 1.95, w: BODY_W, h: 0.4, fontFace: FONT, fontSize: 14, color: GREY });
  s.addText('AI-GENERATED', {
    x: MARGIN, y: 2.5, w: 1.75, h: 0.36, fontFace: FONT, fontSize: 10, bold: true, color: TEAL, align: 'center', valign: 'middle',
    line: { color: TEAL, width: 1 }, rectRadius: 0.05, shape: pres.ShapeType.roundRect,
  });
  if (when) s.addText(`Generated ${when}`, { x: 2.4, y: 2.5, w: 6, h: 0.36, fontFace: FONT, fontSize: 11, color: GREY, valign: 'middle' });
  s.addShape(pres.ShapeType.rect, { x: MARGIN, y: 3.15, w: 0.08, h: 2.3, fill: { color: TEAL }, line: { color: TEAL } });
  s.addText(short || '', { x: MARGIN + 0.3, y: 3.15, w: BODY_W - 0.3, h: 2.3, fontFace: FONT, fontSize: 18, color: NAVY, valign: 'top', fit: 'shrink' });
  if (extra) s.addText(extra, { x: MARGIN, y: 5.7, w: BODY_W, h: 0.4, fontFace: FONT, fontSize: 12, color: GREY });
  return s;
}

function textSlide(pres, title, blocks) {
  const s = pres.addSlide({ masterName: 'REGULATOR' });
  heading(s, title);
  const runs = [];
  blocks.forEach((b, i) => {
    if (b.label) runs.push({ text: b.label, options: { bold: true, color: TEAL, fontSize: 14, breakLine: true, paraSpaceBefore: i ? 14 : 0 } });
    runs.push({ text: b.text || '', options: { color: NAVY, fontSize: 16, breakLine: true, paraSpaceAfter: 6 } });
  });
  s.addText(runs, { x: MARGIN, y: 1.2, w: BODY_W, h: 5.5, fontFace: FONT, valign: 'top', fit: 'shrink' });
  return s;
}

const headCell = (text) => ({ text, options: { bold: true, color: 'FFFFFF', fill: { color: NAVY }, fontSize: 11 } });

function statusCell(status, label) {
  const st = styleOf(status);
  return { text: label || st.word, options: { bold: true, color: st.text, fill: { color: st.fill } } };
}

function tableSlides(pres, title, sub, header, colW, pages) {
  pages.forEach((rows, i) => {
    const s = pres.addSlide({ masterName: 'REGULATOR' });
    heading(s, pages.length > 1 ? `${title} (${i + 1} of ${pages.length})` : title, sub);
    s.addTable([header.map(headCell), ...rows], {
      x: MARGIN, y: sub ? 1.45 : 1.2, w: BODY_W, colW, fontFace: FONT, fontSize: 11, color: NAVY,
      border: { type: 'solid', pt: 0.75, color: BORDER }, valign: 'top', margin: 0.06,
    });
  });
}

function bulletsSlide(pres, title, sub, items) {
  const s = pres.addSlide({ masterName: 'REGULATOR' });
  heading(s, title, sub);
  s.addText(
    items.map((t) => ({ text: t, options: { bullet: true, breakLine: true, paraSpaceAfter: 6 } })),
    { x: MARGIN, y: sub ? 1.5 : 1.2, w: BODY_W, h: 5.3, fontFace: FONT, fontSize: 14, color: NAVY, valign: 'top', fit: 'shrink' },
  );
}

/** Slides for the summary of one regulation (T029 dialog). */
export async function buildRegulationDeck(summary, regulation) {
  const name = (regulation?.abbreviatedTitle || '').trim() || regulation?.title || 'Regulation';
  const pres = await newDeck(`AI summary: ${name}`);
  const due = dueText(regulation?.dueDate);
  titleSlide(pres, {
    kicker: 'Regulator · AI summary of a regulation',
    title: name,
    sub: [regulation?.title && regulation.title !== name ? regulation.title : '', due ? `Due ${due}` : ''].filter(Boolean).join(' · '),
    when: generatedText(summary.generatedAt),
    short: summary.short,
  });
  textSlide(pres, 'The regulation, documents and notes', [
    { label: 'Regulation', text: summary.regulation },
    { label: 'Documents and notes', text: summary.documentsAndNotes },
  ]);
  const units = summary.units || [];
  if (units.length) {
    const rows = units.map((u) => [
      { text: u.name, options: { bold: true } },
      statusCell(u.status, u.statusLabel),
      u.summary || '',
      contactNames(u.contacts),
    ]);
    const pages = paginate(rows, (r) => 0.6 + Math.max(lines(r[2], 75), lines(r[3], 30)));
    tableSlides(pres, 'Status across Business Units', null, ['Business Unit', 'Status', 'Summary', 'Contacts'], [2.2, 2.0, 5.6, 2.53], pages);
  }
  const actions = (summary.actionsNeeded || []).map((a) => (a.unit ? `${a.unit}: ${a.action}` : a.action));
  bulletsSlide(pres, 'Actions needed', null, actions.length ? actions : ['No actions have been entered.']);
  return { pres, fileName: `Regulator-AI-summary-${slug(name)}-${today()}.pptx` };
}

/** Slides for an Insights summary (T031 dialog). */
export async function buildInsightDeck(summary, groupLabel, viewLabel) {
  const label = summary.groupLabel || groupLabel || 'Summary';
  const pres = await newDeck(`AI summary: ${label}`);
  const c = summary.counts || {};
  const countLine =
    c.statuses != null
      ? `${c.statuses} Business Unit status${c.statuses === 1 ? '' : 'es'} across ${c.regulations} regulation${c.regulations === 1 ? '' : 's'}.`
      : '';
  titleSlide(pres, {
    kicker: `Regulator · Insights · ${viewLabel || ''}`.replace(/ · $/, ''),
    title: `AI summary: ${label}`,
    sub: '',
    when: generatedText(summary.generatedAt),
    short: summary.short,
    extra: countLine,
  });
  if (summary.overview) textSlide(pres, 'Overview', [{ text: summary.overview }]);
  const entries = summary.entries || [];
  if (entries.length) {
    const rows = entries.map((e) => [
      { text: [
        { text: e.name, options: { bold: true, breakLine: !!e.dueDate } },
        ...(e.dueDate ? [{ text: `Due ${dueText(e.dueDate)}`, options: { color: GREY, fontSize: 10 } }] : []),
      ] },
      e.unit,
      statusCell(e.status, e.statusLabel),
      e.text || '',
      contactNames(e.contacts),
    ]);
    const pages = paginate(rows, (r) => 0.6 + Math.max(2, lines(r[3], 60), lines(r[4], 24)));
    tableSlides(pres, 'In detail', viewLabel, ['Regulation', 'Business Unit', 'Status', 'Summary', 'Contacts'], [2.4, 1.6, 1.75, 4.6, 1.98], pages);
  }
  if (summary.moreCount) {
    const names = [...(summary.moreNames || [])];
    if (summary.moreCount > names.length) names.push(`and ${summary.moreCount - names.length} more`);
    bulletsSlide(pres, `${summary.moreCount} more not covered in detail`, 'Named here so nothing is left out; open them in Regulator for detail.', names);
  }
  return { pres, fileName: `Regulator-AI-summary-${slug(label)}-${today()}.pptx` };
}

/** Builds and downloads; resolves when the file has been handed to the browser. */
export async function downloadDeck(built) {
  const { pres, fileName } = await built;
  await pres.writeFile({ fileName, compression: true });
  return fileName;
}

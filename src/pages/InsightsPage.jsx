/**
 * InsightsPage - Insights (T030; FR-4.3, FR-4.4, FR-4.6; DL-18), laid out as
 * in the Business Owner's slides of Nov 9 and approved with the example
 * summaries on Nov 10.
 *
 * One page for every role (Admin, SME, User): no role-based summaries; each
 * person narrows the view with the filters.
 *  - Filters: Domain, Business Unit, Country, Region and a due-date range
 *    (the shared RegulationFilterBar, no Status filter). On a first visit
 *    the range is the current calendar year. Filters live in the URL, like
 *    the Roadmap and the Dashboard, so a view can be bookmarked or shared.
 *  - Count line: total regulations (each counted once), the Business Unit
 *    statuses by status (each regulation once per unit, decision 3A), and
 *    how many domains, Business Units and countries are in view.
 *  - Charts: pies for domain and region; bars for country and Business Unit.
 *  - Compliance Overview: one row per status with its count, a link to the
 *    same units on the Dashboard, and (T031) "View summary": the AI summary
 *    of that row, or of the whole view on the "All" row (FR-4.5, FR-4.6).
 *  - The AI disclaimer in fine print at the bottom of the page (DL-19).
 *
 * The counts and charts are worked out in the browser from the regulations
 * the screen already loads (GET /regulations, own company only). The AI
 * summaries come from POST /insights/summary, which applies the same filters
 * on the server.
 */
import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { Link, useSearchParams } from 'react-router-dom';
import { useAuth } from '../context/AuthContext';
import { fetchRegulations, RegulationApiError } from '../api/regulationsApi';
import { fetchBusinessUnits } from '../api/businessUnitsApi';
import ErrorBanner from '../components/ErrorBanner';
import RegulationFilterBar from '../components/RegulationFilterBar';
import StatusSwatch from '../components/StatusSwatch';
import InsightSummaryDialog from '../components/InsightSummaryDialog';
import { BarChart, PieChart } from '../components/InsightsCharts';
import { statusLabel } from '../constants/status';
import {
  businessUnitOptions,
  countActiveFilters,
  distinctOptions,
  filtersFromSearchParams,
  writeFiltersToSearchParams,
} from '../utils/regulationFilters';
import { NOT_SET, STATUS_ORDER, buildInsights, currentYearRange, rangeLabel } from '../utils/insights';

const DISCLAIMER =
  'Generated by AI from information entered in Regulator. Review before using it. Material is for general information only and does not constitute professional or legal advice.';
const summaryButton =
  'text-xs font-semibold text-brand-teal dark:text-teal-300 underline underline-offset-2 hover:no-underline focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-teal rounded';

const FILTER_KEYS = ['q', 'status', 'domain', 'bu', 'country', 'region', 'dueFrom', 'dueTo', 'docs'];

function hasAnyFilterParam(params) {
  return FILTER_KEYS.some((k) => params.has(k));
}

function statusName(key) {
  return key === NOT_SET ? 'Not set' : statusLabel(key);
}

function Stat({ label, value }) {
  return (
    <div className="flex items-baseline gap-1.5">
      <span className="text-h3 font-semibold tabular-nums text-brand-navy dark:text-white">{value}</span>
      <span className="text-xs text-text-secondary dark:text-slate-300">{label}</span>
    </div>
  );
}

export default function InsightsPage() {
  const { idToken } = useAuth();
  const [regulations, setRegulations] = useState([]);
  const [businessUnits, setBusinessUnits] = useState([]);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState(null);
  const [summaryGroup, setSummaryGroup] = useState(null); // T031: the row whose AI summary is open

  const [searchParams, setSearchParams] = useSearchParams();
  const filters = useMemo(() => ({ ...filtersFromSearchParams(searchParams), status: [] }), [searchParams]);
  const setFilters = useCallback(
    (next, { replace = false } = {}) => setSearchParams((prev) => writeFiltersToSearchParams(next, prev), { replace }),
    [setSearchParams]
  );

  // First visit with no filters in the URL: the current calendar year (DL-18).
  const defaulted = useRef(false);
  useEffect(() => {
    if (defaulted.current) return;
    defaulted.current = true;
    if (!hasAnyFilterParam(searchParams)) {
      setSearchParams((prev) => writeFiltersToSearchParams({ ...filtersFromSearchParams(prev), ...currentYearRange() }, prev), {
        replace: true,
      });
    }
  }, [searchParams, setSearchParams]);

  // State is only set inside the promise callbacks (react-hooks/set-state-in-effect).
  useEffect(() => {
    if (!idToken) return undefined;
    let cancelled = false;
    Promise.all([fetchRegulations(idToken), fetchBusinessUnits(idToken)])
      .then(([regList, buList]) => {
        if (cancelled) return;
        setRegulations(regList);
        setBusinessUnits(buList);
        setLoadError(null);
      })
      .catch((err) => {
        if (!cancelled) setLoadError(err instanceof RegulationApiError ? err.message : 'Failed to load Insights.');
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [idToken]);

  const live = useMemo(() => regulations.filter((r) => r.addToRoadmapDashboard === true && !r.hidden), [regulations]);
  const filterOptions = useMemo(
    () => ({
      domain: distinctOptions(live, 'domain'),
      bu: businessUnitOptions(live, businessUnits),
      country: distinctOptions(live, 'country'),
      region: distinctOptions(live, 'region'),
    }),
    [live, businessUnits]
  );
  const model = useMemo(() => buildInsights(regulations, businessUnits, filters), [regulations, businessUnits, filters]);
  const range = rangeLabel(filters);
  const filtered = countActiveFilters(filters) > 0;

  const groupOf = (key) => (key === NOT_SET ? 'not_set' : key);

  const dashboardLink = (statusKey) => {
    const params = writeFiltersToSearchParams({ ...filters, status: [statusKey] }, new URLSearchParams());
    params.set('view', 'bu');
    return `/dashboard?${params.toString()}`;
  };

  return (
    <div className="space-y-4 max-w-6xl">
      <p className="text-body text-text-secondary dark:text-slate-300">
        Where your company&rsquo;s regulations stand, for the filters below. Due dates: <span className="font-semibold text-text-primary dark:text-white">{range}</span>.
      </p>

      {!loading && !loadError && live.length > 0 && (
        <RegulationFilterBar
          filters={filters}
          onChange={setFilters}
          options={filterOptions}
          showStatus={false}
          resultLabel={`${model.total} of ${live.length} regulations in view`}
        />
      )}

      {loading && <p className="text-body text-text-secondary dark:text-slate-400">Loading...</p>}
      {loadError && <ErrorBanner message={loadError} />}

      {!loading && !loadError && live.length === 0 && (
        <p className="p-10 text-center text-body text-text-tertiary dark:text-slate-400 bg-surface-card dark:bg-surface-card-dark border border-border-default dark:border-border-dark rounded-lg">
          No regulations yet. Insights appear once regulations are added.
        </p>
      )}

      {!loading && !loadError && live.length > 0 && (
        <>
          <section
            aria-label="Totals"
            className="bg-surface-card dark:bg-surface-card-dark border border-border-default dark:border-border-dark rounded-lg px-5 py-4 flex flex-wrap items-center gap-x-6 gap-y-3"
          >
            <Stat label={model.total === 1 ? 'regulation' : 'regulations'} value={model.total} />
            <span aria-hidden="true" className="h-6 w-px bg-border-default dark:bg-border-dark" />
            {STATUS_ORDER.map((key) => (
              <div key={key} className="flex items-center gap-1.5">
                <StatusSwatch status={key === NOT_SET ? null : key} size="sm" decorative />
                <span className="text-body font-semibold tabular-nums text-text-primary dark:text-white">{model.statusCounts[key]}</span>
                <span className="text-xs text-text-secondary dark:text-slate-300">{statusName(key)}</span>
              </div>
            ))}
            <span aria-hidden="true" className="h-6 w-px bg-border-default dark:bg-border-dark" />
            <Stat label={model.domains === 1 ? 'domain' : 'domains'} value={model.domains} />
            <Stat label={model.units === 1 ? 'Business Unit' : 'Business Units'} value={model.units} />
            <Stat label={model.countries === 1 ? 'country' : 'countries'} value={model.countries} />
            <p className="basis-full text-xs text-text-secondary dark:text-slate-400">
              Regulations are counted once. Statuses are counted once per Business Unit, because one regulation can have a
              different status in each unit ({model.unitStatuses} Business Unit statuses in view).
            </p>
          </section>

          <div className="grid gap-4 md:grid-cols-2">
            <PieChart title="Regulations by domain" rows={model.byDomain} total={model.total} />
            <PieChart title="Regulations by region" rows={model.byRegion} total={model.total} />
            <BarChart title="Regulations by country" rows={model.byCountry} total={model.total} />
            <BarChart
              title="Regulations by Business Unit"
              rows={model.byUnit}
              total={model.unitStatuses}
              unitNote="A regulation shared by several Business Units is counted under each of them."
            />
          </div>

          <section className="bg-surface-card dark:bg-surface-card-dark border border-border-default dark:border-border-dark rounded-lg">
            <h2 id="compliance-overview" className="px-5 py-3 text-body font-semibold text-text-primary dark:text-white border-b border-border-default dark:border-border-dark">
              Compliance Overview
            </h2>
            <table className="w-full border-collapse" aria-labelledby="compliance-overview">
              <thead className="bg-surface-muted dark:bg-surface-muted-dark">
                <tr>
                  <th scope="col" className="px-5 py-2 text-left text-label uppercase text-text-secondary dark:text-slate-300">Status</th>
                  <th scope="col" className="px-5 py-2 text-right text-label uppercase text-text-secondary dark:text-slate-300">Business Unit statuses</th>
                  <th scope="col" className="px-5 py-2 text-left text-label uppercase text-text-secondary dark:text-slate-300">AI summary</th>
                  <th scope="col" className="px-5 py-2 text-left text-label uppercase text-text-secondary dark:text-slate-300">
                    <span className="sr-only">Open on the Dashboard</span>
                  </th>
                </tr>
              </thead>
              <tbody>
                {STATUS_ORDER.map((key) => (
                  <tr key={key} className="border-t border-border-default dark:border-border-dark">
                    <th scope="row" className="px-5 py-2.5 text-left font-normal">
                      <span className="inline-flex items-center gap-2 text-body text-text-primary dark:text-slate-200">
                        <StatusSwatch status={key === NOT_SET ? null : key} size="sm" decorative />
                        {statusName(key)}
                      </span>
                    </th>
                    <td className="px-5 py-2.5 text-right text-body font-semibold tabular-nums text-text-primary dark:text-white">
                      {model.statusCounts[key]}
                    </td>
                    <td className="px-5 py-2.5">
                      {model.statusCounts[key] > 0 ? (
                        <button type="button" onClick={() => setSummaryGroup(groupOf(key))} className={summaryButton}>
                          View summary<span className="sr-only">: {statusName(key)}</span>
                        </button>
                      ) : (
                        <span className="text-xs text-text-tertiary dark:text-slate-400">&mdash;</span>
                      )}
                    </td>
                    <td className="px-5 py-2.5">
                      {model.statusCounts[key] > 0 && (
                        <Link
                          to={dashboardLink(key)}
                          className="text-xs text-brand-teal dark:text-teal-300 underline underline-offset-2 hover:no-underline focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-teal rounded"
                        >
                          Show on the Dashboard<span className="sr-only">: {statusName(key)}</span>
                        </Link>
                      )}
                    </td>
                  </tr>
                ))}
                <tr className="border-t-2 border-border-strong dark:border-border-dark">
                  <th scope="row" className="px-5 py-2.5 text-left text-body font-semibold text-text-primary dark:text-white">All</th>
                  <td className="px-5 py-2.5 text-right text-body font-semibold tabular-nums text-text-primary dark:text-white">{model.unitStatuses}</td>
                  <td className="px-5 py-2.5">
                    {model.total > 0 && (
                      <button type="button" onClick={() => setSummaryGroup('all')} className={summaryButton}>
                        View summary<span className="sr-only">: everything in view</span>
                      </button>
                    )}
                  </td>
                  <td />
                </tr>
              </tbody>
            </table>
            {filtered && model.total === 0 && (
              <p className="px-5 py-3 text-xs text-text-secondary dark:text-slate-400 border-t border-border-default dark:border-border-dark">
                No regulations match these filters. Widen the due-date range or clear a filter.
              </p>
            )}
          </section>

          {/* DL-19: the disclaimer in fine print at the bottom of every page with AI content. */}
          <p className="text-[11px] leading-snug text-text-secondary dark:text-slate-400">{DISCLAIMER}</p>
        </>
      )}

      {summaryGroup && (
        <InsightSummaryDialog
          group={summaryGroup}
          groupLabel={summaryGroup === 'all' ? 'Everything in view' : statusName(summaryGroup === 'not_set' ? NOT_SET : summaryGroup)}
          filters={filters}
          viewLabel={`due dates ${range}${countActiveFilters({ ...filters, dueFrom: '', dueTo: '' }) > 0 ? ', with filters' : ''}`}
          onClose={() => setSummaryGroup(null)}
        />
      )}
    </div>
  );
}

/**
 * InsightSummaryDialog - the AI summary of one Compliance Overview row on
 * Insights (T031; FR-4.5, FR-4.6; DL-18, DL-19). "All" is the summary of the
 * whole view.
 *
 * Same shape as the regulation summary (AiSummaryDialog), as approved in the
 * example summaries doc (Nov 10):
 *  - the 3-line short version first, then More: an overview and one line per
 *    regulation and Business Unit - red (Action needed) in full with the
 *    unit's contacts, Pending in 2 lines, Compliant / Not set in 1 line;
 *  - anything past about 2 pages is named by title, never dropped silently;
 *  - Generate Slides (second drop): the summary as a .pptx, built in the browser
 *    (only for AI-generated summaries; an empty group has nothing to present);
 *  - AI-generated tag, time generated, Copy (with the disclaimer), Close,
 *    disclaimer in fine print.
 * Status colours, names, dates and contacts come from the data, never from
 * the AI. An empty row needs no AI and shows a plain message.
 */
import { useEffect, useId, useRef, useState } from 'react';
import { useAuth } from '../context/AuthContext';
import { fetchInsightSummary } from '../api/aiApi';
import { ApiError } from '../api/apiClient';
import ErrorBanner from './ErrorBanner';
import StatusSwatch from './StatusSwatch';
import { formatDueDate, parseDueDate } from '../utils/roadmapDates';
import { generatedText, insightSummaryToText } from '../utils/summaryText';

const DISCLAIMER =
  'Generated by AI from information entered in Regulator. Review before using it. Material is for general information only and does not constitute professional or legal advice.';
const linkButton =
  'text-xs font-semibold text-brand-teal dark:text-teal-300 underline underline-offset-2 hover:no-underline focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-teal rounded';

function dueText(iso) {
  const d = parseDueDate(iso);
  return d ? formatDueDate(d) : '';
}

export default function InsightSummaryDialog({ group, groupLabel, filters, viewLabel, onClose }) {
  const { idToken } = useAuth();
  const dialogRef = useRef(null);
  const titleId = useId();
  const fullId = useId();
  const [summary, setSummary] = useState(null);
  const [error, setError] = useState(null);
  const [expanded, setExpanded] = useState(false);
  const [copyNote, setCopyNote] = useState('');
  const [slidesBusy, setSlidesBusy] = useState(false);

  useEffect(() => {
    const dialog = dialogRef.current;
    const opener = document.activeElement;
    if (dialog && !dialog.open) dialog.showModal();
    return () => {
      if (dialog?.open) dialog.close();
      const target = opener && opener.isConnected ? opener : document.getElementById('main-content');
      target?.focus();
    };
  }, []);

  // The filters are fixed for the life of the dialog (it closes when they change).
  const [requested] = useState(() => ({ group, filters }));
  useEffect(() => {
    let cancelled = false;
    fetchInsightSummary(idToken, requested.group, requested.filters)
      .then((data) => {
        if (!cancelled) setSummary(data);
      })
      .catch((err) => {
        if (!cancelled) setError(err instanceof ApiError ? err.message : 'The summary could not be loaded. Please try again.');
      });
    return () => {
      cancelled = true;
    };
  }, [idToken, requested]);

  const copy = async () => {
    if (!summary) return;
    try {
      await navigator.clipboard.writeText(insightSummaryToText(summary, viewLabel));
      setCopyNote(summary.aiGenerated ? 'Copied the full summary, with the disclaimer.' : 'Copied.');
    } catch {
      setCopyNote('Copy didn’t work here. Open More, select the text and copy it instead.');
    }
  };

  // Generate Slides (second drop): built in the browser from this summary, no AI call.
  // pptxgenjs is loaded only on the first click.
  const slides = async () => {
    if (!(summary?.aiGenerated) || slidesBusy) return;
    setSlidesBusy(true);
    setCopyNote('');
    try {
      const { buildInsightDeck, downloadDeck } = await import('../utils/summarySlides');
      await downloadDeck(buildInsightDeck(summary, groupLabel, viewLabel));
      setCopyNote('Slides downloaded (.pptx). They open in PowerPoint and Google Slides.');
    } catch {
      setCopyNote('The slides could not be made. Please try again.');
    } finally {
      setSlidesBusy(false);
    }
  };

  const when = summary ? generatedText(summary.generatedAt) : '';
  const hasDetail = summary && (summary.overview || summary.entries.length > 0 || summary.moreCount > 0);

  return (
    <dialog
      ref={dialogRef}
      aria-labelledby={titleId}
      aria-busy={!summary && !error}
      onCancel={(e) => {
        e.preventDefault();
        onClose();
      }}
      className="m-auto w-full max-w-2xl max-h-[90vh] p-0 overflow-hidden rounded-lg bg-surface-card dark:bg-surface-card-dark text-text-primary dark:text-white border border-border-default dark:border-border-dark shadow-2xl backdrop:bg-brand-navy/50"
    >
      <div className="flex flex-col max-h-[90vh]">
        <header className="flex items-start justify-between gap-3 px-5 py-4 border-b border-border-default dark:border-border-dark">
          <div className="min-w-0">
            <p className="text-xs text-text-secondary dark:text-slate-300">Insights &middot; {viewLabel}</p>
            <h2 id={titleId} className="flex flex-wrap items-center gap-2 text-h3 text-brand-navy dark:text-white">
              {group !== 'all' && <StatusSwatch status={group === 'not_set' ? null : group} size="md" decorative />}
              AI summary: {groupLabel}
              {(!summary || summary.aiGenerated) && (
                <span className="text-[11px] font-semibold uppercase tracking-wide px-1.5 py-0.5 rounded border border-brand-teal text-brand-teal dark:border-teal-300 dark:text-teal-300">
                  AI-generated
                </span>
              )}
            </h2>
          </div>
          <button
            type="button"
            onClick={onClose}
            aria-label="Close"
            className="text-text-secondary dark:text-slate-300 hover:text-brand-teal dark:hover:text-teal-300 text-lg leading-none px-2 py-1 rounded focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-teal"
          >
            &times;
          </button>
        </header>

        <div className="flex-1 overflow-y-auto px-5 py-4 space-y-4">
          {!summary && !error && (
            <p role="status" className="text-body text-text-secondary dark:text-slate-300">
              Writing the summary&hellip; The first time can take up to 30 seconds. After that it opens straight away.
            </p>
          )}
          <ErrorBanner message={error} />

          {summary && (
            <>
              <p className="text-body text-text-primary dark:text-slate-100">{summary.short}</p>
              {summary.counts?.statuses > 0 && (
                <p className="text-xs text-text-secondary dark:text-slate-300">
                  {summary.counts.statuses} Business Unit {summary.counts.statuses === 1 ? 'status' : 'statuses'} across{' '}
                  {summary.counts.regulations} {summary.counts.regulations === 1 ? 'regulation' : 'regulations'}.
                </p>
              )}

              {hasDetail && !expanded && (
                <button type="button" onClick={() => setExpanded(true)} aria-expanded="false" aria-controls={fullId} className={linkButton}>
                  More
                </button>
              )}
              {hasDetail && expanded && (
                <div id={fullId} className="space-y-4">
                  {summary.overview && <p className="text-body">{summary.overview}</p>}
                  {summary.entries.length > 0 && (
                    <ol className="space-y-3">
                      {summary.entries.map((e) => (
                        <li key={`${e.regulationId}-${e.unitCode}`} className="flex gap-2">
                          <StatusSwatch status={e.status} size="sm" decorative className="mt-1" />
                          <div className="min-w-0 space-y-0.5">
                            <p className="text-body">
                              <span className="font-semibold" title={e.title}>{e.name}</span>
                              <span className="text-text-secondary dark:text-slate-300">
                                {' '}&middot; {e.unit} &middot; {e.statusLabel}
                                {e.dueDate && <> &middot; due {dueText(e.dueDate)}</>}
                              </span>
                            </p>
                            <p className="text-body">{e.text}</p>
                            {e.contacts?.length > 0 && (
                              <p className="text-xs text-text-secondary dark:text-slate-300">
                                Contact:{' '}
                                {e.contacts.map((c, i) => (
                                  <span key={`${c.email}-${i}`}>
                                    {i > 0 && ', '}
                                    {c.email ? (
                                      <a href={`mailto:${c.email}`} className="text-brand-teal dark:text-teal-300 underline underline-offset-2 hover:no-underline focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-teal rounded">
                                        {c.name}
                                      </a>
                                    ) : (
                                      c.name
                                    )}
                                  </span>
                                ))}
                              </p>
                            )}
                          </div>
                        </li>
                      ))}
                    </ol>
                  )}
                  {summary.moreCount > 0 && (
                    <div className="rounded-md border border-border-default dark:border-border-dark px-3 py-2 space-y-1">
                      <p className="text-xs font-semibold text-text-primary dark:text-white">
                        {summary.moreCount} more not covered in detail &mdash; narrow the filters to see them in full:
                      </p>
                      <p className="text-xs text-text-secondary dark:text-slate-300">
                        {summary.moreNames.join('; ')}
                        {summary.moreCount > summary.moreNames.length && '; …'}
                      </p>
                    </div>
                  )}
                  <button type="button" onClick={() => setExpanded(false)} aria-expanded="true" aria-controls={fullId} className={linkButton}>
                    Less
                  </button>
                </div>
              )}

              {when && <p className="text-xs text-text-secondary dark:text-slate-300">Generated {when}.</p>}
            </>
          )}
        </div>

        <footer className="px-5 py-3 border-t border-border-default dark:border-border-dark space-y-2">
          <div className="flex flex-wrap items-center gap-2">
            <button
              type="button"
              onClick={copy}
              aria-disabled={!summary}
              className="bg-brand-teal text-white rounded-md px-4 py-2 text-body font-medium aria-disabled:opacity-60 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-teal focus-visible:ring-offset-2 dark:focus-visible:ring-offset-surface-card-dark"
            >
              Copy
            </button>
            <button
              type="button"
              onClick={slides}
              aria-disabled={!(summary?.aiGenerated) || slidesBusy}
              className="rounded-md px-4 py-2 text-body font-medium border border-brand-teal text-brand-teal dark:text-teal-300 dark:border-teal-300 aria-disabled:opacity-60 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-teal"
            >
              {slidesBusy ? 'Generating…' : 'Generate Slides'}
            </button>
            <button
              type="button"
              onClick={onClose}
              className="rounded-md px-4 py-2 text-body border border-border-default dark:border-border-dark text-text-secondary dark:text-slate-300 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-teal"
            >
              Close
            </button>
            <p role="status" className="text-xs text-text-secondary dark:text-slate-300 empty:hidden">
              {copyNote}
            </p>
          </div>
          <p className="text-[11px] leading-snug text-text-secondary dark:text-slate-400">{summary?.disclaimer || DISCLAIMER}</p>
        </footer>
      </div>
    </dialog>
  );
}
